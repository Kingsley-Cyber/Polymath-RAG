"""C0 census: the polymath-v4 repository seen as a code corpus (CODE-KNOWLEDGE-V1 C0, register 11.458).

Counts what C1-C7 would ingest from one repository with the tools that are ALREADY installed (stdlib `ast` / `tomllib`
+ PyYAML): files per language card, parents per the Python card (each class, each top-level function, one module block),
unit sizes in tokens, and the YAML / TOML structure the cards need. Deterministic: no network, no database, no model.

Token counts use tiktoken `cl100k_base` (cached locally; nothing is downloaded) as a PROXY for the lane models'
tokenizers (gpt-oss uses o200k): read them as +-10 %.

Run from the repository root:
    .venv/bin/python docs/wiki/experiments/code-knowledge-c0-2026-09-24/census.py . > census.json
"""
from __future__ import annotations

import ast
import json
import re
import subprocess
import sys
import tomllib
from collections import Counter, defaultdict
from pathlib import Path

import yaml

try:
    import tiktoken

    _ENC = tiktoken.get_encoding("cl100k_base")

    def ntok(text: str) -> int:
        return len(_ENC.encode(text, disallowed_special=()))

    TOKENIZER = "tiktoken cl100k_base (proxy)"
except Exception:  # noqa: BLE001 — no cached encoding: fall back to a stated estimate, never a silent one
    def ntok(text: str) -> int:
        return (len(text) + 3) // 4

    TOKENIZER = "chars/4 estimate (tiktoken encoding not cached)"

# spec §1 "Selection": generated, vendored and lock files are skipped with a receipt
SKIP_DIRS = ("vendor/", "Packages/", "DevPackages/", "node_modules/", "__pycache__/", "dist/", "build/", ".venv/")
GENERATED_MARKS = re.compile(r"(?i)(generated by|do not edit|autogenerated|auto-generated)")
SIZE_BANDS = (500, 2000, 4000, 8000)          # tokens: unit size bands reported for §12 (oversized units)
PY_EXT = (".py", ".pyi")
YAML_EXT = (".yaml", ".yml")
TOML_EXT = (".toml",)
LUAU_EXT = (".luau", ".lua")


def tracked_files(root: Path) -> list[str]:
    out = subprocess.run(["git", "-C", str(root), "ls-files"], capture_output=True, text=True, check=True).stdout
    return [p for p in out.splitlines() if p]


def area_of(path: str) -> str:
    head = path.split("/", 1)[0]
    if path.startswith("docs/wiki/experiments/"):
        return "docs/wiki/experiments"
    return head if "/" in path else "(root)"


def skip_reason(path: str, text: str | None) -> str | None:
    if any(f"/{d}" in f"/{path}" for d in SKIP_DIRS):
        return "vendored_or_build_dir"
    if path.endswith(".lock"):
        return "lock_file"
    if path.endswith(("_pb2.py", "_pb2_grpc.py")):
        return "generated_protobuf"
    if text is not None and GENERATED_MARKS.search("\n".join(text.splitlines()[:5])):
        return "generated_header"
    if text is not None and text and max(len(line) for line in text.splitlines() or [""]) > 2000:
        return "minified_long_line"
    return None


def band(tokens: int) -> str:
    for b in SIZE_BANDS:
        if tokens <= b:
            return f"<={b}"
    return f">{SIZE_BANDS[-1]}"


def segment(lines: list[str], node: ast.AST) -> str:
    start = getattr(node, "lineno", 1)
    if getattr(node, "decorator_list", None):
        start = min([start] + [d.lineno for d in node.decorator_list])
    end = getattr(node, "end_lineno", start) or start
    return "\n".join(lines[start - 1:end])


def is_main_guard(node: ast.AST) -> bool:
    if not isinstance(node, ast.If):
        return False
    t = node.test
    return (isinstance(t, ast.Compare) and isinstance(t.left, ast.Name) and t.left.id == "__name__"
            and any(isinstance(c, ast.Constant) and c.value == "__main__" for c in t.comparators))


ROUTE_METHODS = {"get", "post", "put", "patch", "delete", "websocket", "api_route", "route"}


def is_route(dec: ast.AST) -> bool:
    return (isinstance(dec, ast.Call) and isinstance(dec.func, ast.Attribute) and dec.func.attr in ROUTE_METHODS
            and bool(dec.args) and isinstance(dec.args[0], ast.Constant) and isinstance(dec.args[0].value, str))


def python_file(path: str, text: str) -> dict:
    rec: dict = {"path": path, "tokens": ntok(text), "lines": text.count("\n") + 1}
    try:
        tree = ast.parse(text, filename=path)
    except SyntaxError as exc:
        rec["parse_error"] = f"{exc.msg} (line {exc.lineno})"
        return rec
    lines = text.splitlines()
    is_test = "/tests/" in f"/{path}" or Path(path).name.startswith("test_")
    parents: list[dict] = []
    module_stmts: list[ast.AST] = []
    symbols = Counter()
    for node in tree.body:
        if isinstance(node, ast.ClassDef):
            methods = [n for n in node.body if isinstance(n, (ast.FunctionDef, ast.AsyncFunctionDef))]
            child_tokens = [ntok(segment(lines, m)) for m in methods]
            parents.append({"kind": "class", "name": node.name, "line": node.lineno,
                            "tokens": ntok(segment(lines, node)), "children": len(methods),
                            "largest_child_tokens": max(child_tokens, default=0)})
            symbols["class"] += 1
            for m in methods:
                symbols["property" if any(isinstance(d, ast.Name) and d.id == "property" for d in m.decorator_list)
                        else ("async_method" if isinstance(m, ast.AsyncFunctionDef) else "method")] += 1
                if is_test and m.name.startswith("test"):
                    symbols["test"] += 1
        elif isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef)):
            tok = ntok(segment(lines, node))
            parents.append({"kind": "function", "name": node.name, "line": node.lineno, "tokens": tok,
                            "children": 1, "largest_child_tokens": tok})
            symbols["async_function" if isinstance(node, ast.AsyncFunctionDef) else "function"] += 1
            if is_test and node.name.startswith("test"):
                symbols["test"] += 1
            if any(is_route(d) for d in node.decorator_list):
                symbols["route"] += 1
        else:
            module_stmts.append(node)
            if is_main_guard(node):
                symbols["entrypoint"] += 1
            if isinstance(node, (ast.Assign, ast.AnnAssign)):
                targets = node.targets if isinstance(node, ast.Assign) else [node.target]
                symbols["constant"] += sum(1 for t in targets if isinstance(t, ast.Name) and t.id.isupper())
    # the module block = imports, constants, the __main__ guard (only statements outside classes / functions)
    body_only_docstring = (len(module_stmts) == 1 and isinstance(module_stmts[0], ast.Expr)
                           and isinstance(getattr(module_stmts[0], "value", None), ast.Constant))
    if module_stmts and not body_only_docstring:
        tok = sum(ntok(segment(lines, n)) for n in module_stmts)
        parents.append({"kind": "module_block", "name": "<module>", "line": module_stmts[0].lineno, "tokens": tok,
                        "children": 1, "largest_child_tokens": tok})
    imports = sum(len(n.names) for n in ast.walk(tree) if isinstance(n, (ast.Import, ast.ImportFrom)))
    calls = sum(1 for n in ast.walk(tree) if isinstance(n, ast.Call))
    rec.update({"is_test": is_test, "parents": parents, "symbols": dict(symbols), "import_names": imports,
                "call_sites": calls})
    return rec


def yaml_dialect(doc) -> str:
    if not isinstance(doc, dict):
        return "non_mapping"
    keys = set(map(str, doc))
    if ("on" in keys or "True" in keys) and "jobs" in keys:   # PyYAML 1.1 reads a bare `on:` key as True
        return "github_actions"
    if "services" in keys:
        return "docker_compose"
    if {"apiVersion", "kind"} <= keys:
        return "kubernetes"
    if "openapi" in keys or "swagger" in keys:
        return "openapi"
    return "generic"


def yaml_file(path: str, text: str) -> dict:
    rec: dict = {"path": path, "tokens": ntok(text), "lines": text.count("\n") + 1,
                 "comment_lines": sum(1 for line in text.splitlines() if line.lstrip().startswith("#")),
                 "starts_with_document_marker": text.lstrip().startswith("---")}
    try:
        docs = list(yaml.safe_load_all(text))
        anchors = aliases = 0
        for ev in yaml.parse(text, Loader=yaml.SafeLoader):
            if isinstance(ev, yaml.AliasEvent):
                aliases += 1
            elif getattr(ev, "anchor", None):
                anchors += 1
    except yaml.YAMLError as exc:
        rec["parse_error"] = str(exc).splitlines()[0][:160]
        return rec
    sections = sum(len(d) for d in docs if isinstance(d, dict))
    rec.update({"documents": len(docs), "top_level_sections": sections, "anchors": anchors, "aliases": aliases,
                "dialects": sorted({yaml_dialect(d) for d in docs})})
    return rec


def toml_tables(obj, prefix="") -> tuple[int, int, int]:
    """(tables, arrays_of_tables, keys) — recursively, the way the TOML card defines parents."""
    tables = arrays = keys = 0
    for k, v in obj.items():
        if isinstance(v, dict):
            tables += 1
            t, a, n = toml_tables(v, f"{prefix}{k}.")
            tables, arrays, keys = tables + t, arrays + a, keys + n
        elif isinstance(v, list) and v and all(isinstance(x, dict) for x in v):
            arrays += 1
            for x in v:
                t, a, n = toml_tables(x, f"{prefix}{k}.")
                tables, arrays, keys = tables + t, arrays + a, keys + n
        else:
            keys += 1
    return tables, arrays, keys


def toml_file(path: str, text: str) -> dict:
    rec: dict = {"path": path, "tokens": ntok(text), "lines": text.count("\n") + 1}
    try:
        data = tomllib.loads(text)
    except tomllib.TOMLDecodeError as exc:
        rec["parse_error"] = str(exc)[:160]
        return rec
    t, a, k = toml_tables(data)
    rec.update({"tables": t, "arrays_of_tables": a, "keys": k,
                "known_schema": Path(path).name in {"pyproject.toml", "Cargo.toml", "wally.toml", "selene.toml",
                                                     "stylua.toml", "aftman.toml", "rokit.toml"}})
    return rec


def main(root: Path) -> dict:
    files = tracked_files(root)
    ext_counts = Counter(Path(p).suffix.lower() or "(none)" for p in files)
    per_card: dict[str, list[dict]] = defaultdict(list)
    skipped: list[dict] = []
    for p in files:
        suffix = Path(p).suffix.lower()
        card = ("python" if suffix in PY_EXT else "yaml" if suffix in YAML_EXT else "toml" if suffix in TOML_EXT
                else "luau" if suffix in LUAU_EXT else None)
        if card is None:
            continue
        fp = root / p
        if not fp.is_file():
            continue
        text = fp.read_text(encoding="utf-8", errors="replace")
        why = skip_reason(p, text)
        if why:
            skipped.append({"path": p, "card": card, "reason": why})
            continue
        if card == "python":
            per_card[card].append(python_file(p, text))
        elif card == "yaml":
            per_card[card].append(yaml_file(p, text))
        elif card == "toml":
            per_card[card].append(toml_file(p, text))
        else:
            per_card[card].append({"path": p, "tokens": ntok(text)})

    py = per_card["python"]
    by_area: dict[str, Counter] = defaultdict(Counter)
    parent_bands, child_bands, file_bands = Counter(), Counter(), Counter()
    symbols_total = Counter()
    largest_parents: list[dict] = []
    for f in py:
        a = by_area[area_of(f["path"])]
        a["files"] += 1
        a["tokens"] += f["tokens"]
        file_bands[band(f["tokens"])] += 1
        if "parse_error" in f:
            a["parse_errors"] += 1
            continue
        a["parents"] += len(f["parents"])
        a["test_files"] += int(f["is_test"])
        a["call_sites"] += f["call_sites"]
        a["import_names"] += f["import_names"]
        symbols_total.update(f["symbols"])
        for par in f["parents"]:
            a[f"parents_{par['kind']}"] += 1
            parent_bands[band(par["tokens"])] += 1
            child_bands[band(par["largest_child_tokens"])] += 1
            largest_parents.append({"path": f["path"], "kind": par["kind"], "name": par["name"],
                                    "line": par["line"], "tokens": par["tokens"], "children": par["children"],
                                    "largest_child_tokens": par["largest_child_tokens"]})
    largest_parents.sort(key=lambda r: -r["tokens"])
    largest_files = sorted(({"path": f["path"], "tokens": f["tokens"], "lines": f["lines"],
                             "parents": len(f.get("parents", []))} for f in py), key=lambda r: -r["tokens"])[:15]

    yml = per_card["yaml"]
    toml_ = per_card["toml"]
    return {
        "census": "CODE-KNOWLEDGE-V1 C0 repository census",
        "root_commit": subprocess.run(["git", "-C", str(root), "rev-parse", "HEAD"], capture_output=True,
                                      text=True, check=True).stdout.strip(),
        "tokenizer": TOKENIZER,
        "tracked_files": len(files),
        "tracked_by_extension_top": dict(ext_counts.most_common(20)),
        "skipped_with_receipt": {"count": len(skipped), "by_reason": dict(Counter(s["reason"] for s in skipped)),
                                 "items": skipped[:40]},
        "python": {
            "files": len(py),
            "parse_errors": [{"path": f["path"], "error": f["parse_error"]} for f in py if "parse_error" in f],
            "tokens_total": sum(f["tokens"] for f in py),
            "parents_total": sum(len(f.get("parents", [])) for f in py),
            "by_area": {k: dict(v) for k, v in sorted(by_area.items(), key=lambda kv: -kv[1]["files"])},
            "file_token_bands": dict(file_bands),
            "parent_token_bands": dict(parent_bands),
            "largest_child_token_bands": dict(child_bands),
            "symbols": dict(symbols_total),
            "largest_files": largest_files,
            "largest_parents": largest_parents[:20],
        },
        "yaml": {
            "files": len(yml),
            "parse_errors": [{"path": f["path"], "error": f["parse_error"]} for f in yml if "parse_error" in f],
            "tokens_total": sum(f["tokens"] for f in yml),
            "top_level_sections": sum(f.get("top_level_sections", 0) for f in yml),
            "documents": sum(f.get("documents", 0) for f in yml),
            "multi_document_files": sum(1 for f in yml if f.get("documents", 0) > 1),
            "files_with_anchors_or_aliases": sum(1 for f in yml if f.get("anchors") or f.get("aliases")),
            "comment_lines_pyyaml_drops": sum(f.get("comment_lines", 0) for f in yml),
            "files_starting_with_document_marker": sum(1 for f in yml if f.get("starts_with_document_marker")),
            "dialects": dict(Counter(d for f in yml for d in f.get("dialects", []))),
            "per_file": [{k: f.get(k) for k in ("path", "tokens", "documents", "top_level_sections", "anchors",
                                             "aliases", "comment_lines", "dialects")} for f in yml],
        },
        "toml": {
            "files": len(toml_),
            "parse_errors": [{"path": f["path"], "error": f["parse_error"]} for f in toml_ if "parse_error" in f],
            "tables": sum(f.get("tables", 0) for f in toml_),
            "arrays_of_tables": sum(f.get("arrays_of_tables", 0) for f in toml_),
            "keys": sum(f.get("keys", 0) for f in toml_),
            "spans_available_from_tomllib": False,
            "per_file": [{k: f.get(k) for k in ("path", "tokens", "tables", "arrays_of_tables", "keys",
                                             "known_schema")} for f in toml_],
        },
        "luau": {"files": len(per_card["luau"])},
    }


if __name__ == "__main__":
    print(json.dumps(main(Path(sys.argv[1] if len(sys.argv) > 1 else ".").resolve()), indent=1, sort_keys=False))
